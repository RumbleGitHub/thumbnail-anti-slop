// Real-image validation kit (extends the Quality Lab; generates no images and calls no API).
//
//   npm run lab:kit -- --baseline=<path to an older checkout's src/lib/simpleEngine/engine.ts>
//                      [--models=OPENAI_GPT_IMAGE_2_5_SUNBURST,MIDJOURNEY_V8_2]
//
// Writes tests/quality-lab/reports/real-image-kit.md: for six representative golden cases, the
// BEFORE and AFTER prompts for identical inputs and model settings, the reference photos the
// creator must supply, the usage notes, and a scoring sheet for the generated images.
// Prompt text is not visual evidence: only the scored images are.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { GOLDEN_CASES } from './golden-cases.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..', '..');
const arg = name => process.argv.find(a => a.startsWith(`--${name}=`))?.split('=').slice(1).join('=');

// Same flag as the deployed default (complementary engines off) for both versions.
process.env.COMPLEMENTARY_ENGINES_ENABLED = 'false';

const after = await import(pathToFileURL(path.join(root, 'src/lib/simpleEngine/engine.ts')).href);
const baselinePath = arg('baseline');
const before = baselinePath ? await import(pathToFileURL(path.resolve(baselinePath)).href) : null;
const MODELS = (arg('models') || 'OPENAI_GPT_IMAGE_2_5_SUNBURST,MIDJOURNEY_V8_2').split(',');

// Six representative cases (golden case id -> what to prepare and what to look for).
const KIT = [
  { id: '01_ps2_covers', focus: 'Capas reais de GTA San Andreas e God of War legíveis; PS2 correto; rosto da referência.', photos: 'Sua foto de rosto (PESSOA). Opcional: fotos das duas capas como PRODUTO.' },
  { id: '13_non_tech_object_no_person', focus: 'Feijoada real e apetitosa; nenhuma pessoa, mão ou rosto inventado; luz natural.', photos: 'Nenhuma.' },
  { id: '04_named_products_no_reference', focus: 'Dois aparelhos distintos e identificáveis (iPhone 17 Pro e Galaxy S26 Ultra), sem fusão nem genéricos.', photos: 'Nenhuma.' },
  { id: '08_no_environment_conservative', focus: 'Identidade: o rosto gerado é reconhecivelmente o da foto (idade, formato, assimetria).', photos: 'Sua foto de rosto (PESSOA).' },
  { id: '11_exact_portuguese_text', focus: 'Pessoa segurando o Steam Deck com mãos plausíveis; texto exato "NÃO COMPRE".', photos: 'Sua foto de rosto (PESSOA).' },
  { id: '09_target_image_locked', focus: 'Composição, pose e roupa da imagem-alvo mantidas; só o rosto muda.', photos: 'Imagem-alvo (IMAGEM_ALVO) e sua foto de rosto (PESSOA).' },
];

const DEFECTS = [
  ['Produto incorreto', 'produto errado, genérico, fundido ou com botões/portas inventados'],
  ['Capa falsa', 'arte ou título de capa inventado / ilegível (só casos com capas)'],
  ['Falha de identidade', 'rosto não reconhecível como o da referência'],
  ['Luz artificial', 'neon, rim light sem fonte, brilho plástico, HDR'],
  ['Interação física', 'mãos/dedos/pegada impossíveis, objeto atravessando a mão'],
  ['Composição fraca', 'assunto pequeno ou ilegível em 120px, poluição visual'],
  ['Texto incorreto', 'texto diferente do pedido, letras derretidas, texto extra'],
];

const BASE_INPUT = {
  videoTitle: '', ideaDescription: '', thumbnailText: '', textTreatment: 'AUTO', references: [],
  aspectRatio: '16:9', stylePreset: 'Natural', realismLevel: 'Alto', preserveFace: false, preserveProduct: false, approachIndex: 0,
};

const md = [];
md.push('# Real-image validation kit');
md.push('');
md.push(`Generated by \`tests/quality-lab/real-image-kit.mjs\` on ${new Date().toISOString().slice(0, 10)}. Models: ${MODELS.join(', ')}.`);
md.push(before ? `BEFORE = engine at \`${path.basename(path.resolve(baselinePath, '..', '..', '..', '..'))}\`; AFTER = this working tree.` : 'No --baseline given: only AFTER prompts are listed.');
md.push('');
md.push('**This file contains prompts, not results.** Visual quality is only proven by generating both prompts with the same model and settings and scoring the images below.');
md.push('');
md.push('## Procedure (about 30-45 min per model)');
md.push('');
md.push('1. Use one model and keep its settings fixed (same quality, aspect ratio 16:9, no style presets). Use the same reference photos for BEFORE and AFTER.');
md.push('2. For each case, generate **2 images from BEFORE** and **2 from AFTER** (a new chat/session per prompt, so earlier images do not leak in).');
md.push('3. Attach references exactly as listed. For Midjourney V8.2, follow the AFTER notes (Edit Model, "Attach to prompt"); for BEFORE, attach the same images the same way, so only the text differs.');
md.push('4. Without knowing which is which (ask someone to shuffle, or rename the files A/B), score each image 0/1/2 per defect: 0 = absent, 1 = minor, 2 = clearly wrong. Mark n/a when the defect cannot occur.');
md.push('5. Sum per prompt version. A version wins a case only if its total is lower in both images. Note the worst defect you see.');
md.push('');
md.push('| Defect | What counts |');
md.push('|---|---|');
for (const [d, w] of DEFECTS) md.push(`| ${d} | ${w} |`);
md.push('');

for (const k of KIT) {
  const c = GOLDEN_CASES.find(g => g.id === k.id);
  md.push(`## ${k.id} — ${c.title}`);
  md.push('');
  md.push(`- Title: ${c.input.videoTitle}`);
  md.push(`- Idea: ${c.input.ideaDescription}`);
  if (c.input.thumbnailText) md.push(`- Exact text: "${c.input.thumbnailText}"`);
  md.push(`- References to prepare: ${k.photos}`);
  md.push(`- Look for: ${k.focus}`);
  md.push('');
  for (const model of MODELS) {
    const input = { ...BASE_INPUT, ...c.input, targetModel: model };
    const a = after.generateSimpleThumbnail(input);
    md.push(`### ${model}`);
    md.push('');
    if (before) {
      md.push('**BEFORE**');
      md.push('');
      md.push('```text');
      md.push(before.generateSimpleThumbnail(input).finalPrompt);
      md.push('```');
      md.push('');
    }
    md.push('**AFTER**');
    md.push('');
    md.push('```text');
    md.push(a.finalPrompt);
    md.push('```');
    if (a.modelNotes?.length) {
      md.push('');
      md.push('Notes for the creator (not part of the prompt):');
      for (const n of a.modelNotes) md.push(`- ${n}`);
    }
    md.push('');
    md.push('| Image | ' + DEFECTS.map(d => d[0]).join(' | ') + ' | Total |');
    md.push('|---|' + DEFECTS.map(() => '---').join('|') + '|---|');
    for (const label of ['BEFORE 1', 'BEFORE 2', 'AFTER 1', 'AFTER 2']) {
      if (!before && label.startsWith('BEFORE')) continue;
      md.push(`| ${label} |` + DEFECTS.map(() => '  ').join('|') + '|  |');
    }
    md.push('');
  }
}

const out = path.join(here, 'reports', 'real-image-kit.md');
fs.writeFileSync(out, md.join('\n'));
console.log(`Wrote ${path.relative(root, out)} (${KIT.length} cases x ${MODELS.length} models${before ? ', before/after' : ''}).`);
